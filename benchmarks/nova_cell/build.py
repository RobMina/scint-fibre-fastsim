"""Build the NOVA-CELL benchmark: reference tree, the three configurations' submissions, their scores, the
leaderboard and the Codabench bundle.

    python benchmarks/nova_cell/build.py OUT_DIR

runs validation/nova_cell/compare.py into OUT_DIR (reference/, submissions/<config>/, scores_<config>.json,
record.json), writes benchmarks/nova_cell/reference_results/LEADERBOARD.md from the record, and builds
OUT_DIR/codabench/competition_bundle.zip with hep-simbench (solution: the reference solution, configuration C) plus
OUT_DIR/codabench/solution_submission.zip, a results submission that scores on the bundle.
"""
from __future__ import annotations

import argparse
import json
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
VAL = HERE.parents[1] / "validation" / "nova_cell"
REFERENCE_SOLUTION = "C_frontend_timing"
NAMES = {"A_defaults": "Weak baseline A: package defaults, nothing fitted",
         "B_train_fit": "Baseline B: optics fitted on the train split; timing time_res / sqrt(PE)",
         "C_frontend_timing": "**Reference solution C**: B with the front-end timing bound plus a fitted floor"}
WORKFLOWS = ("NC-TB", "NC-FIBRE", "NC-FD", "NC-TND", "NC-TFD")


def _logo(n: int = 64) -> bytes:
    """A plain 64 x 64 PNG (placeholder logo): a green band on grey, written without an imaging library."""
    import struct
    import zlib
    rows = b"".join(b"\x00" + b"".join(bytes((40, 170, 90)) if abs(y - n // 2) < 8 else bytes((60, 60, 70))
                                       for _ in range(n)) for y in range(n))
    chunk = lambda t, d: struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", n, n, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows)) + chunk(b"IEND", b""))


def leaderboard(record: dict) -> str:
    rows = ["| Configuration | Validity score (mean) | " + " | ".join(f"{w} f32 / f64" for w in WORKFLOWS) + " |",
            "|---|---|" + "---|" * len(WORKFLOWS)]
    for cn, c in record["configurations"].items():
        if cn not in NAMES:                       # D (study T2) uses a test histogram: not a submission
            continue
        cells = []
        for w in WORKFLOWS:
            r = c["workflows"][w]
            cells.append(f"{r['float32']['validity']:.2f} / {r['float64']['validity']:.2f}")
        rows.append(f"| {NAMES[cn]} | {c['validity_mean']:.3f} | " + " | ".join(cells) + " |")
    v = record["verdicts"]
    return ("# NOVA-CELL leaderboard (reference results)\n\n"
            "Generated by `benchmarks/nova_cell/build.py` from `validation/nova_cell/record.json` "
            f"(criteria sha256 `{record['criteria_sha256'][:12]}...`; the commit is in the record; CPU). Validity per workflow and dtype = (1 - flagged fraction of histograms) x (fraction of yields "
            "passing); the score is the mean over workflows and dtypes.\n\n" + "\n".join(rows) +
            f"\n\nDeclared pass lines: optics validated **{v['optics_validated']}**, timing validated "
            f"**{v['timing_validated']}**, float32 / float64 agreement **{v['dtype_agreement']}**.\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("out", type=Path)
    a = ap.parse_args(argv)
    sys.path.insert(0, str(VAL))
    import compare
    from hepsimbench.codabench import build

    record_path = a.out / "record.json"
    compare.main([str(a.out), "--record", str(record_path)])
    record = json.loads(record_path.read_text())
    (HERE / "reference_results").mkdir(exist_ok=True)
    (HERE / "reference_results" / "LEADERBOARD.md").write_text(leaderboard(record))
    sol = a.out / "submissions" / REFERENCE_SOLUTION
    zip_path = build(a.out / "codabench", reference=a.out / "reference", solution=sol,
                     title="NOVA-CELL: NOvA cell response against public data", overview=HERE / "README.md",
                     commit_title="model and commit that produced the submission", task_name="NOvA cell response")
    from hepsimbench.codabench import zip_tree
    (a.out / "codabench" / "bundle" / "logo.png").write_bytes(_logo())       # the template names a logo
    zip_tree(a.out / "codabench" / "bundle", zip_path)
    sub = a.out / "codabench" / "solution_submission.zip"
    with zipfile.ZipFile(sub, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(sol.rglob("hists.json")):
            z.write(f, arcname=f.relative_to(sol).as_posix())
    print(zip_path)
    print(sub)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
